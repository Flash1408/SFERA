classdef EffectDetector < handle
    % EffectDetector
    %
    % High-level component responsible for detecting predefined
    % and custom effects in input signals.
    %
    % The detector coordinates the analysis process by creating
    % effect objects through EffectsFactory and executing them.
    %
    % Main responsibilities:
    %   - detecting a specific predefined effect
    %   - performing a full analysis across predefined effects
    %   - detecting custom user-defined effects
    %   - retaining the context of the last analysis

    properties (Access = private)
        % Context generated by the last executed effect analysis.
        lastContext

        % Name of the effect used in the last analysis.
        lastEffectName
    end

    methods
        function [isDetected, howDetected] = detect(obj, y, t, effectName)
            % DETECT Analyzes a signal for predefined effects.
            %
            % INPUT:
            %   y          -> Signal values.
            %   t          -> Corresponding time samples.
            %   effectName -> Optional name of the predefined effect.
            %                 If omitted, all predefined effects are analyzed.
            %
            % OUTPUT:
            %   isDetected -> True if an effect is detected.
            %   howDetected -> Name of the detected effect, or a message
            %                  indicating that no effect was detected.
            %
            % When a specific effect is requested, only that effect is analyzed.
            % Otherwise, all predefined effects are analyzed according to
            % their detection priority, stopping at the first positive result.

            % Specific-effect detection.
            if nargin >= 4 && ~isempty(effectName)

                [isDetected, howDetected] = obj.analyzeEffect( ...
                    y, t, 'predefined',effectName, true);

                return;
            end

            % Full detection.
            detectionOrder = {
                'Exponential Divergence'
                'Permanent Oscillations'
                'Damped Oscillations'
                'Divergent Oscillations'
                'Cubic Radix Trend'
                'Fifth Radix Trend'
                'Arctangent Trend'
                'Runge Trend'
                'Sum of Sinusoids'
            };

            isDetected = false;
            howDetected = 'No effect detected';

            for k = 1:numel(detectionOrder)

                effectName = detectionOrder{k};

                [isDetected, howDetected] = obj.analyzeEffect( ...
                    y, t, 'predefined', effectName, false);

                if isDetected
                    return;
                end
            end
        end

        function [isDetected, howDetected] = detectCustom( ...
                obj, y, t, userModel, options)
            % DETECTCUSTOM Analyzes a signal using a user-defined model.
            %
            % INPUT:
            %   y         -> Signal values.
            %   t         -> Corresponding time samples.
            %   userModel -> UserModel object defining the custom model.
            %   options   -> BaseOptions object containing the general
            %                analysis configuration.
            %
            % OUTPUT:
            %   isDetected -> True if the custom model is accepted.
            %   howDetected -> Name of the custom model, or a message
            %                  indicating that no effect was detected.
            %
            % The custom effect is analyzed through the common
            % analyzeEffect method.

            effectData.userModel = userModel;
            effectData.options = options;

            [isDetected, howDetected] = obj.analyzeEffect( ...
                y, t, 'custom', effectData, false);
        end

        function context = getContext(obj)
            % GETCONTEXT Returns the context of the last effect analysis.
            %
            % OUTPUT:
            %   context -> EffectContext generated by the last analysis.
            %
            % An error is raised if no analysis has been executed yet.

            if isempty(obj.lastContext)
                error('EffectDetector:NoAnalysisAvailable', ...
                    'No effect analysis has been performed yet.');
            end

            context = obj.lastContext;
        end

        function effectName = getLastEffectName(obj)
            % GETLASTEFFECTNAME Returns the name of the last analyzed effect.
            %
            % OUTPUT:
            %   effectName -> Name of the effect used in the last analysis.
            %
            % An error is raised if no analysis has been executed yet.

            if isempty(obj.lastEffectName)
                error('EffectDetector:NoAnalysisAvailable', ...
                    'No effect analysis has been performed yet.');
            end

            effectName = obj.lastEffectName;
        end
    end

    methods (Access = private)
        function [isDetected, howDetected] = analyzeEffect( ...
                obj, y, t, effectType, effectData, isSpecificDetection)
            % ANALYZEEFFECT Creates and executes an effect analysis.
            %
            % INPUT:
            %   y                    -> Signal values.
            %   t                    -> Corresponding time samples.
            %   effectType           -> Type of effect ('predefined' or 'custom').
            %   effectData           -> Effect name or custom model definition.
            %   isSpecificDetection  -> Indicates whether a predefined effect
            %                            was explicitly requested.
            %
            % OUTPUT:
            %   isDetected -> True if the effect is detected.
            %   howDetected -> Name of the detected effect, or a message
            %                  indicating that no effect was detected.
            %
            % The method handles effect creation, configuration, execution,
            % and storage of the resulting analysis context.

            switch effectType

                case 'predefined'

                    effectName = effectData;
                    effect = EffectsFactory.createEffect(effectName);

                    % Preserve the legacy threshold used when Damped
                    % Oscillations is explicitly requested.
                    if isSpecificDetection && ...
                            strcmp(effectName, 'Damped Oscillations')

                        options = DampedOscillationOptions();
                        options.threshold = 0.7;

                        effect.setOptions(options);
                    end

                case 'custom'

                    userModel = effectData.userModel;
                    options = effectData.options;

                    effect = EffectsFactory.createCustomEffect( ...
                        userModel, options);

                    effectName = char(userModel.modelName);

                otherwise

                    error('EffectDetector:InvalidEffectType', ...
                        'Unsupported effect type: %s.', effectType);
            end

            % Execute the effect analysis.
            isDetected = effect.analyze(y, t);

            % Store the result of the last executed analysis.
            obj.lastContext = effect.getContext();
            obj.lastEffectName = effectName;

            if isDetected
                howDetected = effectName;
            else
                howDetected = 'No effect detected';
            end
        end
    end
end